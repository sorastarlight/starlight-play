const assert=require('node:assert/strict');const {inspect}=require('../tools/check-new-table-access');
const base='create table public.example(id uuid primary key);';
const reset='revoke all on public.example from PUBLIC, anon, authenticated, service_role;';
assert(inspect(base).some(x=>x.includes('revoke')));
assert.deepEqual(inspect(base+reset),[]);
assert(inspect(base+reset+'grant select on public.example to authenticated;').some(x=>x.includes('RLS')));
assert.deepEqual(inspect(base+reset+'alter table public.example enable row level security;grant select on public.example to authenticated;'),[]);
assert(inspect(base+reset+'grant select on public.example to PUBLIC;').some(x=>x.includes('PUBLIC')));
assert(inspect(base+'-- '+reset).length>0);
assert(inspect(base+"select '"+reset+"';").length>0);
assert(inspect(base+'revoke all on public.other from PUBLIC,anon,authenticated,service_role;').length>0);
assert(inspect('create table no_schema(id int);').some(x=>x.includes('schema-qualify')));
assert.deepEqual(inspect('create table private.archive(id int);'),[]);
assert.deepEqual(inspect('create temporary table scratch(id int);'),[]);
assert.deepEqual(inspect('create table "public"."example"(id int);'+reset),[]);
assert(inspect(base+reset+'create table public.other(id int);').some(x=>x.startsWith('public.other')));
assert.deepEqual(inspect('create function private.fixture() returns void language plpgsql as $$begin create table public.dynamic(id int);end$$;'),[]);
assert(inspect("-- don't inherit grants\n"+base+"select 'text';").length>0);
assert(inspect("/* don't inherit grants */"+base+"select 'text';").length>0);
