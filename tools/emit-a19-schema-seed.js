#!/usr/bin/env node
/**
 * Emit unapplied A19-SCHEMA seed SQL from the offline pin.
 * Does not connect to Postgres or pokeapi.co.
 *
 *   node tools/emit-a19-schema-seed.js
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { loadPin, verifyManifest } = require("./lib/gen9-ref");
const { proposedStreamlinkFriendship } = require("./lib/gen9-ref-proposals");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "supabase", "unapplied", "a19-schema", "seed");
const CONTENT = "sl-ref-20261013-227b573";
const GMAX_IDS = [10195, 10196, 10197, 10198, 10199, 10200, 10201, 10202, 10203, 10204, 10205, 10206];
const CHAMPIONS_IDS = [10278, 10279, 10280, 10281];
const POLICY_IDS = new Set([...GMAX_IDS, ...CHAMPIONS_IDS]);
const BATCH = 200;

function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

function sqlStr(v) {
  if (v == null) return "NULL";
  return `'${String(v).replace(/'/g, "''")}'`;
}

function sqlNum(v) {
  if (v == null || v === "") return "NULL";
  const n = Number(v);
  if (!Number.isFinite(n)) throw new Error(`bad number ${v}`);
  return String(n);
}

function sqlBool(v) {
  return v ? "TRUE" : "FALSE";
}

function sqlTextArray(arr) {
  const list = Array.isArray(arr) ? arr : [];
  return `ARRAY[${list.map(sqlStr).join(", ")}]::text[]`;
}

function header(title) {
  return [
    "-- A19-SCHEMA UNAPPLIED SEED (issue #22)",
    "-- DO NOT RUN against live Supabase.",
    `-- ${title}`,
    `-- content_build ${CONTENT}`,
    "-- Generated by tools/emit-a19-schema-seed.js from data/gen9-ref/.",
    "",
    "BEGIN;",
    ""
  ].join("\n");
}

function footer() {
  return "\nCOMMIT;\n";
}

function writeBatched(file, title, columns, rows, conflict) {
  const chunks = [];
  chunks.push(header(title));
  for (let i = 0; i < rows.length; i += BATCH) {
    const slice = rows.slice(i, i + BATCH);
    chunks.push(`INSERT INTO ${columns.table} (${columns.cols}) VALUES`);
    chunks.push(slice.map((row) => `  (${row})`).join(",\n"));
    chunks.push(`${conflict};\n`);
  }
  if (!rows.length) chunks.push("-- no rows\n");
  chunks.push(footer());
  fs.writeFileSync(file, chunks.join("\n"));
}

function evoUid(row) {
  return [
    row.fromDex,
    row.toDex,
    row.trigger || "unknown",
    row.minLevel == null ? "" : row.minLevel,
    row.itemId == null ? "" : row.itemId,
    row.heldItemId == null ? "" : row.heldItemId,
    row.tradeSpeciesId == null ? "" : row.tradeSpeciesId
  ].join(":");
}

function main() {
  const pin = loadPin();
  const errors = verifyManifest(pin);
  if (errors.length) throw new Error(errors.join("; "));
  if (pin.meta.contentBuild !== CONTENT) {
    throw new Error(`unexpected contentBuild ${pin.meta.contentBuild}`);
  }
  fs.mkdirSync(OUT, { recursive: true });

  const manifestSha = pin.manifest.files["manifest.json"] || sha256(fs.readFileSync(path.join(ROOT, "data", "gen9-ref", "manifest.json")));

  fs.writeFileSync(path.join(OUT, "00_meta.sql"), [
    header("ref_meta"),
    "INSERT INTO private.ref_meta (content_build, ruleset_id, pokeapi_commit, built_at, source_kind, pin_manifest_sha256, license_note) VALUES",
    `  (${sqlStr(CONTENT)}, ${sqlStr(pin.meta.rulesetId)}, ${sqlStr(pin.meta.pokeapiCommit)}, ${sqlStr(pin.meta.builtAt)}, 'offline-pin', ${sqlStr(manifestSha)}, ${sqlStr(pin.meta.licenseNote)})`,
    "ON CONFLICT (content_build) DO UPDATE SET",
    "  ruleset_id = EXCLUDED.ruleset_id,",
    "  pokeapi_commit = EXCLUDED.pokeapi_commit,",
    "  built_at = EXCLUDED.built_at,",
    "  source_kind = EXCLUDED.source_kind,",
    "  pin_manifest_sha256 = EXCLUDED.pin_manifest_sha256,",
    "  license_note = EXCLUDED.license_note;",
    footer()
  ].join("\n"));

  writeBatched(
    path.join(OUT, "01_natures.sql"),
    "ref_natures",
    { table: "private.ref_natures", cols: "content_build, id, slug, name, up_stat, down_stat" },
    pin.natures.map((n) => [sqlStr(CONTENT), sqlNum(n.id), sqlStr(n.slug), sqlStr(n.name), sqlStr(n.upStat), sqlStr(n.downStat)].join(", ")),
    "ON CONFLICT (content_build, id) DO UPDATE SET slug = EXCLUDED.slug, name = EXCLUDED.name, up_stat = EXCLUDED.up_stat, down_stat = EXCLUDED.down_stat"
  );

  writeBatched(
    path.join(OUT, "02_species.sql"),
    "ref_species (F1 derived streamlink friendship; pin JSON unchanged)",
    { table: "private.ref_species", cols: "content_build, dex, slug, gender_rate, pokeapi_base_friendship, streamlink_base_friendship, capture_rate, hatch_counter, is_legendary, is_mythical, mapping_status" },
    pin.species.map((s) => {
      const mapped = proposedStreamlinkFriendship(s.baseFriendship);
      if (!mapped.ok) throw new Error(`friendship ${s.dex}`);
      return [
        sqlStr(CONTENT), sqlNum(s.dex), sqlStr(s.slug), sqlNum(s.genderRate),
        sqlNum(s.baseFriendship), sqlNum(mapped.streamlinkValue),
        sqlNum(s.captureRate), sqlNum(s.hatchCounter),
        sqlBool(s.isLegendary), sqlBool(s.isMythical), sqlStr(s.mappingStatus)
      ].join(", ");
    }),
    "ON CONFLICT (content_build, dex) DO UPDATE SET slug = EXCLUDED.slug, gender_rate = EXCLUDED.gender_rate, pokeapi_base_friendship = EXCLUDED.pokeapi_base_friendship, streamlink_base_friendship = EXCLUDED.streamlink_base_friendship, capture_rate = EXCLUDED.capture_rate, hatch_counter = EXCLUDED.hatch_counter, is_legendary = EXCLUDED.is_legendary, is_mythical = EXCLUDED.is_mythical, mapping_status = EXCLUDED.mapping_status"
  );

  writeBatched(
    path.join(OUT, "03_forms.sql"),
    "ref_forms",
    { table: "private.ref_forms", cols: "content_build, form_id, dex, form_key, form_label, kind, is_base, pokeapi_pokemon_id, mapping_status, types, height_m, weight_kg, hp, atk, def, spa, spd, spe, learnset_status, learnset_version_group, learnset_resolution" },
    pin.forms.map((f) => [
      sqlStr(CONTENT), sqlNum(f.formId), sqlNum(f.dex), sqlStr(f.formKey), sqlStr(f.formLabel),
      sqlStr(f.kind), sqlBool(f.isBase), sqlNum(f.pokeapiPokemonId), sqlStr(f.mappingStatus),
      sqlTextArray(f.types), sqlNum(f.heightM), sqlNum(f.weightKg),
      sqlNum(f.hp), sqlNum(f.atk), sqlNum(f.def), sqlNum(f.spa), sqlNum(f.spd), sqlNum(f.spe),
      sqlStr(f.learnsetStatus), sqlStr(f.learnsetVersionGroup), sqlStr(f.learnsetResolution)
    ].join(", ")),
    "ON CONFLICT (content_build, form_id) DO UPDATE SET dex = EXCLUDED.dex, form_key = EXCLUDED.form_key, form_label = EXCLUDED.form_label, kind = EXCLUDED.kind, is_base = EXCLUDED.is_base, pokeapi_pokemon_id = EXCLUDED.pokeapi_pokemon_id, mapping_status = EXCLUDED.mapping_status, types = EXCLUDED.types, height_m = EXCLUDED.height_m, weight_kg = EXCLUDED.weight_kg, hp = EXCLUDED.hp, atk = EXCLUDED.atk, def = EXCLUDED.def, spa = EXCLUDED.spa, spd = EXCLUDED.spd, spe = EXCLUDED.spe, learnset_status = EXCLUDED.learnset_status, learnset_version_group = EXCLUDED.learnset_version_group, learnset_resolution = EXCLUDED.learnset_resolution"
  );

  writeBatched(
    path.join(OUT, "04_abilities.sql"),
    "ref_abilities",
    { table: "private.ref_abilities", cols: "content_build, ability_id, slug, generation, is_main_series" },
    pin.abilities.map((a) => [sqlStr(CONTENT), sqlNum(a.abilityId), sqlStr(a.slug), sqlNum(a.generation), sqlBool(a.isMainSeries)].join(", ")),
    "ON CONFLICT (content_build, ability_id) DO UPDATE SET slug = EXCLUDED.slug, generation = EXCLUDED.generation, is_main_series = EXCLUDED.is_main_series"
  );

  writeBatched(
    path.join(OUT, "05_form_abilities.sql"),
    "ref_form_abilities",
    { table: "private.ref_form_abilities", cols: "content_build, form_id, slot, ability_id, is_hidden" },
    pin.formAbilities.map((a) => [sqlStr(CONTENT), sqlNum(a.formId), sqlStr(a.slot), sqlNum(a.abilityId), sqlBool(a.isHidden)].join(", ")),
    "ON CONFLICT (content_build, form_id, slot) DO UPDATE SET ability_id = EXCLUDED.ability_id, is_hidden = EXCLUDED.is_hidden"
  );

  writeBatched(
    path.join(OUT, "06_moves.sql"),
    "ref_moves",
    { table: "private.ref_moves", cols: "content_build, move_id, slug, type, damage_class, pp, power, accuracy" },
    pin.moves.map((m) => [sqlStr(CONTENT), sqlNum(m.moveId), sqlStr(m.slug), sqlStr(m.type), sqlStr(m.damageClass), sqlNum(m.pp), sqlNum(m.power), sqlNum(m.accuracy)].join(", ")),
    "ON CONFLICT (content_build, move_id) DO UPDATE SET slug = EXCLUDED.slug, type = EXCLUDED.type, damage_class = EXCLUDED.damage_class, pp = EXCLUDED.pp, power = EXCLUDED.power, accuracy = EXCLUDED.accuracy"
  );

  writeBatched(
    path.join(OUT, "07_learnsets.sql"),
    "ref_learnsets",
    { table: "private.ref_learnsets", cols: "content_build, form_id, version_group, method, level, move_id, sort_order" },
    pin.learnsets.map((r) => [sqlStr(CONTENT), sqlNum(r.formId), sqlStr(r.versionGroup), sqlStr(r.method), sqlNum(r.level), sqlNum(r.moveId), sqlNum(r.order || 0)].join(", ")),
    "ON CONFLICT (content_build, form_id, version_group, method, level, move_id, sort_order) DO NOTHING"
  );

  writeBatched(
    path.join(OUT, "08_evolutions.sql"),
    "ref_evolutions",
    { table: "private.ref_evolutions", cols: "content_build, evo_uid, from_dex, to_dex, trigger, min_level, item_id, held_item_id, trade_species_id" },
    pin.evolutions.map((e) => [
      sqlStr(CONTENT), sqlStr(evoUid(e)), sqlNum(e.fromDex), sqlNum(e.toDex),
      sqlStr(e.trigger || "unknown"), sqlNum(e.minLevel), sqlNum(e.itemId),
      sqlNum(e.heldItemId), sqlNum(e.tradeSpeciesId)
    ].join(", ")),
    "ON CONFLICT (content_build, evo_uid) DO UPDATE SET from_dex = EXCLUDED.from_dex, to_dex = EXCLUDED.to_dex, trigger = EXCLUDED.trigger, min_level = EXCLUDED.min_level, item_id = EXCLUDED.item_id, held_item_id = EXCLUDED.held_item_id, trade_species_id = EXCLUDED.trade_species_id"
  );

  writeBatched(
    path.join(OUT, "09_obtain.sql"),
    "ref_obtain (G1/C1 form ids forced fail-closed; pin obtain.json unchanged)",
    { table: "private.ref_obtain", cols: "content_build, form_id, dex, channel, normal_encounter_enabled, admin_targetable, event_targetable, enabled" },
    pin.obtain.map((o) => {
      const blocked = POLICY_IDS.has(Number(o.formId));
      return [
        sqlStr(CONTENT), sqlNum(o.formId), sqlNum(o.dex),
        sqlStr(blocked ? "special" : o.channel),
        sqlBool(blocked ? false : o.normalEncounterEnabled),
        sqlBool(blocked ? false : o.adminTargetable),
        sqlBool(blocked ? false : o.eventTargetable),
        sqlBool(blocked ? false : o.enabled)
      ].join(", ");
    }),
    "ON CONFLICT (content_build, form_id) DO UPDATE SET dex = EXCLUDED.dex, channel = EXCLUDED.channel, normal_encounter_enabled = EXCLUDED.normal_encounter_enabled, admin_targetable = EXCLUDED.admin_targetable, event_targetable = EXCLUDED.event_targetable, enabled = EXCLUDED.enabled"
  );

  const policies = [
    ...GMAX_IDS.map((id) => ({
      id, policy: "G1", persist: "base", transform: "gigantamax",
      notes: "G1: persist Kantonian base. Gigantamax is battle-only. Not a wild/grant form."
    })),
    ...CHAMPIONS_IDS.map((id) => ({
      id, policy: "C1", persist: "base", transform: "mega",
      notes: "C1: persist base. Champions/Z-A mega fail-closed for wild/grant."
    }))
  ];
  writeBatched(
    path.join(OUT, "10_form_policies.sql"),
    "ref_form_policies G1/C1",
    { table: "private.ref_form_policies", cols: "content_build, form_id, policy_id, persist_as, wild_allowed, grant_allowed, transform, notes" },
    policies.map((p) => [sqlStr(CONTENT), sqlNum(p.id), sqlStr(p.policy), sqlStr(p.persist), "FALSE", "FALSE", sqlStr(p.transform), sqlStr(p.notes)].join(", ")),
    "ON CONFLICT (content_build, form_id) DO UPDATE SET policy_id = EXCLUDED.policy_id, persist_as = EXCLUDED.persist_as, wild_allowed = EXCLUDED.wild_allowed, grant_allowed = EXCLUDED.grant_allowed, transform = EXCLUDED.transform, notes = EXCLUDED.notes"
  );

  const files = fs.readdirSync(OUT).filter((n) => n.endsWith(".sql")).sort();
  const seedManifest = {
    contentBuild: CONTENT,
    emitter: "tools/emit-a19-schema-seed.js",
    appliedToSupabase: false,
    counts: {
      natures: pin.natures.length,
      species: pin.species.length,
      forms: pin.forms.length,
      abilities: pin.abilities.length,
      formAbilities: pin.formAbilities.length,
      moves: pin.moves.length,
      learnsets: pin.learnsets.length,
      evolutions: pin.evolutions.length,
      obtain: pin.obtain.length,
      formPolicies: policies.length
    },
    files: Object.fromEntries(files.map((name) => {
      const abs = path.join(OUT, name);
      return [name, { sha256: sha256(fs.readFileSync(abs)), bytes: fs.statSync(abs).size }];
    }))
  };
  fs.writeFileSync(path.join(OUT, "manifest.json"), `${JSON.stringify(seedManifest, null, 2)}\n`);
  fs.writeFileSync(path.join(OUT, "README.md"), [
    "# Unapplied pin seed",
    "",
    "DO NOT RUN against live Supabase.",
    "",
    `content_build: \`${CONTENT}\``,
    "Regenerate: `node tools/emit-a19-schema-seed.js`",
    "",
    "Load order after `001_private_ref_tables.sql`: `00` through `10`.",
    "G1/C1 overrides live only in these SQL files. `data/gen9-ref/obtain.json` is unchanged.",
    "F1 `streamlink_base_friendship` is derived at emit time. `data/gen9-ref/species.json` is unchanged.",
    ""
  ].join("\n"));

  console.log(JSON.stringify(seedManifest.counts, null, 2));
}

main();
